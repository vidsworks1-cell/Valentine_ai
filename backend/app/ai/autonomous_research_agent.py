class HypothesisTemplate:
    """Represents a generated quantitative hypothesis."""
    def __init__(
        self,
        hypothesis_id: str,
        title: str,
        statement: str,
        rationale: str,
        category: str,
        control_params: Dict[str, Any],
        candidate_params: Dict[str, Any]
    ):
        self.hypothesis_id = hypothesis_id
        self.title = title
        self.statement = statement
        self.rationale = rationale
        self.category = category
        self.control_params = control_params
        self.candidate_params = candidate_params
        self.created_at = datetime.now(timezone.utc).isoformat()
        self.associated_experiment_id: Optional[str] = None
        self.status: str = "GENERATED" # GENERATED, EXPERIMENT_DESIGNED, IN_TESTING, COMPLETED
        self.final_verdict: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "hypothesis_id": self.hypothesis_id,
            "title": self.title,
            "statement": self.statement,
            "rationale": self.rationale,
            "category": self.category,
            "control_params": self.control_params,
            "candidate_params": self.candidate_params,
            "created_at": self.created_at,
            "associated_experiment_id": self.associated_experiment_id,
            "status": self.status,
            "final_verdict": self.final_verdict
        }

class AutonomousResearchAgent:
    """
    Autonomous Research Agent for Lumina AI.
    
    The Architectural Leap:
    Instead of only optimizing existing rules, Lumina autonomously generates new quantitative hypotheses:
    - "ATR multiplier of 1.8 outperforms 2.0 during ranging markets."
    - "Mean Reversion performs poorly after funding rate exceeds 0.08%."
    - "Momentum entries improve when 4H RSI exceeds 60."
    
    Workflow:
    1. Hypothesize: Synthesizes novel hypotheses from market memory & trade journals.
    2. Design: Converts hypothesis into a multi-variant paper experiment.
    3. Test: Executes paper trades in parallel alongside live production.
    4. Evaluate: Calculates statistical significance (t-test, p-value, Sharpe ratio delta).
    5. Recommend & Adopt: Recommends production adoption only when evidence statistically proves superior out-of-sample performance.
    """
    _instance: Optional['AutonomousResearchAgent'] = None

    def __init__(self):
        self._generated_hypotheses: Dict[str, HypothesisTemplate] = {}
        self._research_journal: List[Dict[str, Any]] = []
        self._seed_initial_hypotheses()

    @classmethod
    def get_instance(cls) -> 'AutonomousResearchAgent':
        if cls._instance is None:
            cls._instance = AutonomousResearchAgent()
        return cls._instance

