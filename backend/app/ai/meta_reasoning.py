import logging
import time
import random
from datetime import datetime, timezone
from typing import Dict, Any, List, Optional, Tuple

logger = logging.getLogger("lumina.ai.meta_reasoning")

class MetaReasoningEngine:
    """
    Meta-Reasoning Layer ("Second Brain") for Lumina.
    
    Acts as a second-tier cognitive supervisor that reviews candidate trade setups
    generated by the primary AI signal generation engine.
    
    Before every trade commitment, Lumina asks itself:
    "Why do I believe this trade deserves capital?"
    
    Evaluates 7 Core Quantitative & Qualitative Pillars:
    1. Market Structure (0-100): Level clarity, breakout validity & trend geometry
    2. Liquidity (0-100): Orderbook depth, spread tightness, liquidation sweep potential
    3. Volume (0-100): Relative volume surge (RVOL) & volume profile expansion
    4. Momentum (0-100): Multi-oscillator alignment & directional impulse velocity
    5. Higher Timeframe Agreement (0-100): 4H/1D macro trend alignment
    6. News & Event Risk (0-100): Sentiment stability & macroeconomic calendar risk
    7. Regime Compatibility (0-100): Strategy synergy with active market regime
    
    Only setups meeting the minimum Meta-Reasoning Conviction Threshold (>= 70/100)
    are approved for capital commitment.
    """
    _instance: Optional['MetaReasoningEngine'] = None

    def __init__(self):
        self._last_debate_transcript: Optional[Dict[str, Any]] = None
        self._debate_history: List[Dict[str, Any]] = []
        self._total_debates_count: int = 0
        self._approved_count: int = 0
        self._rejected_count: int = 0
        self._min_conviction_threshold: float = 70.0 # 70 / 100

    @classmethod
    def get_instance(cls) -> 'MetaReasoningEngine':
        if cls._instance is None:
            cls._instance = MetaReasoningEngine()
        return cls._instance

    async def conduct_meta_reasoning_debate(
        self,
        candidate_setup: Dict[str, Any]
    ) -> Tuple[bool, Dict[str, Any]]:
        """
        Executes internal second-brain debate reviewing candidate trade setup.
        Returns (is_approved: bool, debate_audit: Dict[str, Any]).
        """
        symbol = candidate_setup.get("symbol", "UNKNOWN").upper()
        side = candidate_setup.get("side", "BUY").upper()
        strategy = candidate_setup.get("strategy_used", candidate_setup.get("strategy", "General"))
        entry_price = float(candidate_setup.get("entry_price", candidate_setup.get("price", 0.0)))
        regime = str(candidate_setup.get("market_regime", "TRENDING")).upper()
        confidence = float(candidate_setup.get("confidence_score", 0.80))
        atr = float(candidate_setup.get("atr", entry_price * 0.01))

        # 1. Score Market Structure (Support/Resistance & Trend Geometry)
        rel_atr = (atr / entry_price) if entry_price > 0 else 0.01
        if 0.005 <= rel_atr <= 0.02:
            market_structure_score = 88.0
            ms_note = "Clear structural levels with optimal ATR dispersion."
        elif rel_atr < 0.005:
            market_structure_score = 65.0
            ms_note = "Low volatility compression; potential false breakout risk."
        else:
            market_structure_score = 60.0
            ms_note = "Elevated ATR noise near structural levels."

        # 2. Score Liquidity (Orderbook Depth & Sweep Targets)
        from app.trading.onchain_liquidation_pulse import OnChainLiquidationPulseEngine
        liq_pulse = await OnChainLiquidationPulseEngine.get_instance().get_liquidation_heatmap(symbol)
        magnet_dir = liq_pulse.get("magnet_direction", "NEUTRAL")
        liq_aligned = (side == "BUY" and "UPWARD" in magnet_dir) or (side == "SELL" and "DOWNWARD" in magnet_dir)
        if liq_aligned:
            liquidity_score = 92.0
            liq_note = f"Strong orderbook liquidity alignment towards magnet sweep ({magnet_dir})."
        else:
            liquidity_score = 72.0
            liq_note = "Adequate orderbook depth with neutral liquidation sweep bias."

        # 3. Score Volume (RVOL & Volume Profile Expansion)
        volatility_squeeze = candidate_setup.get("squeeze_info", {}).get("squeeze_state", "NORMAL")
        if volatility_squeeze == "SQUEEZE_FIRING":
            volume_score = 95.0
            vol_note = "Squeeze firing with explosive relative volume expansion."
        elif volatility_squeeze == "SQUEEZE_ACTIVE":
            volume_score = 68.0
            vol_note = "Volume compression active; awaiting breakout confirmation."
        else:
            volume_score = 78.0
            vol_note = "Sustained institutional volume flow above 20-period average."

        # 4. Score Momentum (Oscillator Alignment & Impulse Velocity)
        if confidence >= 0.88:
            momentum_score = 92.0
            mom_note = "High impulse velocity across fast and slow momentum oscillators."
        elif confidence >= 0.80:
            momentum_score = 82.0
            mom_note = "Positive momentum momentum alignment in trade direction."
        else:
            momentum_score = 68.0
            mom_note = "Moderate momentum velocity near key decision boundary."

        # 5. Score Higher Timeframe Agreement (4H/1D & MTF Alignment)
        try:
            from app.trading.mtf_confirmation import MTFConfirmationGuard
            price_val = candidate_setup.get("entry_price", 0.0)
            strat_val = candidate_setup.get("strategy_used") or candidate_setup.get("strategy")
            passed_mtf, mtf_align_pct, mtf_details = await MTFConfirmationGuard.get_instance().evaluate_mtf_alignment(
                symbol=symbol,
                side=side,
                price=price_val,
                strategy=strat_val
            )
            if passed_mtf:
                htf_score = min(95.0, max(75.0, mtf_align_pct * 1.1))
                htf_note = f"4H/1D and MTF timeframes strongly aligned ({mtf_align_pct:.1f}%)."
            else:
                htf_score = max(30.0, mtf_align_pct * 0.8)
                htf_note = f"Counter-trend trade relative to MTF structure ({mtf_align_pct:.1f}% vs required {mtf_details.get('required_threshold_pct', 66.0):.1f}%)."
        except Exception as me:
            logger.warning(f"MTF evaluation in MetaReasoning debate failed: {me}")
            htf_score = 60.0
            htf_note = "Higher timeframe multi-timeframe alignment baseline unconfirmed."

        # 6. Score News & Event Risk
        try:
            from app.ai.sentiment_engine import MarketSentimentEngine
            sentiment_data = await MarketSentimentEngine.get_instance().analyze_sentiment(symbol)
            sent_score = abs(sentiment_data.get("composite_sentiment_score", 0.0))
            if sent_score > 60.0:
                news_score = 60.0
                news_note = "High social/news volatility event underway; caution required."
            elif sent_score < 20.0:
                news_score = 90.0
                news_note = "Low macroeconomic news risk environment; baseline sentiment stable."
            else:
                news_score = 80.0
                news_note = "Normal news background noise without imminent macro shocks."
        except Exception:
            news_score = 85.0
            news_note = "Standard news risk parameters evaluated."

        # 7. Score Regime Compatibility
        if ("TREND" in regime and "Breakout" in strategy) or ("RANGE" in regime and "Mean Reversion" in strategy):
            regime_score = 95.0
            regime_note = f"Perfect synergy between {strategy} strategy and {regime} market regime."
        elif "VOLATILE" in regime:
            regime_score = 75.0
            regime_note = f"Elevated volatility regime detected for {strategy}."
        else:
            regime_score = 80.0
            regime_note = f"Acceptable regime alignment ({regime})."

        # Calculate Weighted Meta-Reasoning Conviction Score
        weights = {
            "market_structure": 0.15,
            "liquidity": 0.15,
            "volume": 0.15,
            "momentum": 0.15,
            "higher_timeframe": 0.15,
            "news_risk": 0.10,
            "regime_compatibility": 0.15
        }

        overall_conviction = round(
            (market_structure_score * weights["market_structure"]) +
            (liquidity_score * weights["liquidity"]) +
            (volume_score * weights["volume"]) +
            (momentum_score * weights["momentum"]) +
            (htf_score * weights["higher_timeframe"]) +
            (news_score * weights["news_risk"]) +
            (regime_score * weights["regime_compatibility"]),
            1
        )

        is_approved = overall_conviction >= self._min_conviction_threshold

        # Construct Internal Debate Transcript
        debate_question = f"Why do I believe {symbol} {side} (${entry_price:.2f}) deserves capital?"
        
        if is_approved:
            debate_conclusion = (
                f"✅ CAPITAL APPROVED (Conviction: {overall_conviction}/100 >= {self._min_conviction_threshold}). "
                f"Second brain confirms robust confluence across Market Structure ({market_structure_score:.0f}), "
                f"Liquidity ({liquidity_score:.0f}), Momentum ({momentum_score:.0f}), and HTF ({htf_score:.0f})."
            )
            self._approved_count += 1
        else:
            debate_conclusion = (
                f"🚫 CAPITAL DENIED (Conviction: {overall_conviction}/100 < {self._min_conviction_threshold}). "
                f"Second brain rejected setup due to insufficient conviction across pillars."
            )
            self._rejected_count += 1

        self._total_debates_count += 1

        pillar_scores = {
            "market_structure": {"score": market_structure_score, "note": ms_note, "weight": "15%"},
            "liquidity": {"score": liquidity_score, "note": liq_note, "weight": "15%"},
            "volume": {"score": volume_score, "note": vol_note, "weight": "15%"},
            "momentum": {"score": momentum_score, "note": mom_note, "weight": "15%"},
            "higher_timeframe_agreement": {"score": htf_score, "note": htf_note, "weight": "15%"},
            "news_risk": {"score": news_score, "note": news_note, "weight": "10%"},
            "regime_compatibility": {"score": regime_score, "note": regime_note, "weight": "15%"}
        }

        transcript = {
            "symbol": symbol,
            "side": side,
            "entry_price": entry_price,
            "strategy": strategy,
            "debate_question": debate_question,
            "overall_conviction_score": overall_conviction,
            "required_conviction_threshold": self._min_conviction_threshold,
            "is_approved": is_approved,
            "debate_conclusion": debate_conclusion,
            "pillar_scores": pillar_scores,
            "timestamp": time.time(),
            "timestamp_iso": datetime.now(timezone.utc).isoformat()
        }

        self._last_debate_transcript = transcript
        self._debate_history.append(transcript)
        if len(self._debate_history) > 100:
            self._debate_history.pop(0)

        logger.info(
            f"🧠 [META-REASONING DEBATE] {symbol} {side} (${entry_price:.2f}): "
            f"Question: '{debate_question}' ==> Outcome: {debate_conclusion}"
        )

        return is_approved, transcript

    def get_meta_reasoning_summary(self) -> Dict[str, Any]:
        """
        Returns summary of Second Brain meta-reasoning engine state and history.
        """
        approval_rate = round((self._approved_count / max(1, self._total_debates_count)) * 100.0, 1)
        return {
            "last_debate_transcript": self._last_debate_transcript,
            "total_debates_conducted": self._total_debates_count,
            "approved_debates_count": self._approved_count,
            "rejected_debates_count": self._rejected_count,
            "meta_approval_rate_pct": approval_rate,
            "conviction_threshold": self._min_conviction_threshold,
            "recent_debates": self._debate_history[-10:]
        }
